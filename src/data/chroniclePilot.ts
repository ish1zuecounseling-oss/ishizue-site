function resolve(x: PilotSeed): PilotTask {
  const talk = TALK[x.key]
  const lvId = x.key.slice(0, x.key.indexOf(':'))
  const cat = x.key.slice(x.key.indexOf(':') + 1, x.key.lastIndexOf(':'))
  const idx = Number(x.key.slice(x.key.lastIndexOf(':') + 1))
  const lines = talk?.lines ?? []
  const tr = refsFor(lvId, cat, idx)
  const st = tr?.start
  const where = st ? (st.where ?? st.r.where) : undefined
  const min = st ? (st.min ?? st.r.min) : undefined
  const who = x.who ?? (x.kind === 'self' ? '場面' : '相談者')
  return {
    key: x.key,
    kind: x.kind ?? 'client',
    who,
    twistWho: x.twistWho ?? who,
    lv: x.lv ?? `Lv.${lvId.replace('lv', '')}`,
    title: x.title ?? talk?.title ?? x.key,
    purpose: x.purpose,
    observe: x.observe,
    phrases: x.phrases ?? lines.filter(l => !l.startsWith('避けたい')),
    why: x.why,
    avoid: x.avoid ?? lines.filter(l => l.startsWith('避けたい')).map(l => l.replace(/^避けたい[::]\s*/, '')),
    apply: x.apply ?? (talk?.byType ? TALK_TYPES.map(tp => `${tp.label}:${talk.byType![tp.id]}`) : []),
    ask: x.ask,
    ansLabel: x.ansLabel,
    scene1: x.scene1,
    scene2: x.scene2,
    twist: x.twist,
    look: x.look,
    refs: x.refs ?? (st ? [`まず読む:${st.r.t}${where ? ` ${where}` : ''}${min ? `、約${min}分` : ''}`] : (tr?.refs ?? []).slice(0, 2).map(r => `参考:${r.t}`)),
  }
}

/** 練習できる課題(等級の順) */
const ORDER = Object.keys(TALK)
export const PILOT: PilotTask[] = SEEDS.map(resolve).sort((a, b) => ORDER.indexOf(a.key) - ORDER.indexOf(b.key))
