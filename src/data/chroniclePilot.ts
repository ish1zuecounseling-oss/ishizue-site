// 最初の5課題は、文書「成長の書 トーク集」の「試作:7項目(5課題)」タブと同じ内容。
// そのあと等級ごとに順に広げている(87課題の答え・構成は変えない)。
// key は chronicleTalk.ts / chronicleRefs.ts と同じ「等級id:カテゴリ名:課題の番号(0から)」。
// 段階2の場面(scene2)は、段階1から人物・職種だけを変えたもの。評価する力・難しさ・面接の回数はそろえてある。
// これは練習の仕組みの試作で、臨床能力を証明するものではない。希死念慮・安全計画の内容は専門資料とSVで確認を続ける。
//
// 書かなかった項目は、ほかのデータから引く(トーク集を直せば、練習にも反映される)。
//   お手本の言い回し = トーク集の「避けたい」以外の行 / 避けたい言い方 = トーク集の「避けたい」の行
//   相手の反応がちがうとき = トーク集の反応タイプ別 / 根拠資料 = その課題の「まず読む」
// kind:client=相談者とのやり取り(既定) / explain=後進などに説明する / self=自分にかける言葉

import { TALK, TALK_TYPES } from './chronicleTalk'
import { refsFor } from './chronicleRefs'

export type PilotKind = 'client' | 'explain' | 'self'

/** 書く内容。省略できる項目は、ほかのデータから引く */
export interface PilotSeed {
  key: string
  kind?: PilotKind
  /** 場面の言葉を言う人(既定:相談者) */
  who?: string
  /** 段階3の思いがけない反応を言う人・起きる場面(既定:who と同じ) */
  twistWho?: string
  lv?: string
  title?: string
  purpose: string
  observe: { obs: string; hyp: string; check: string; act: string }
  phrases?: string[]
  why: string
  avoid?: string[]
  apply?: string[]
  /** 回答欄で書くもの(「何を書けばいいか」を一言で) */
  ask: string
  /** 回答欄の見出し(種類ごとの既定を変えたいときだけ) */
  ansLabel?: string
  /** 場面。sit=状況、say=相談者の言葉(ないときは状況だけ) */
  scene1: { sit: string; say?: string }
  scene2: { sit: string; say?: string }
  twist: string
  look: string[]
  refs?: string[]
}
/** 画面で使う形(省略した項目を埋めたもの) */
export interface PilotTask extends Required<Omit<PilotSeed, 'who' | 'twistWho' | 'ansLabel'>> { who: string; twistWho: string; ansLabel?: string }

