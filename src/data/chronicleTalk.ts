// ── 書いた言葉から、関係しそうなトーク集の項目を探す ──
// 外部AIは使わない。漢字・カタカナを含む2文字の組を手がかりに、出現の珍しさで重みをつけて近さを測る(TF-IDF・コサイン類似度)。
// ひらがなだけの2文字(「して」「です」など)は、どの文にも出るので手がかりにしない。
const isKey = (s: string) => /[一-鿿゠-ヿＡ-Ｚａ-ｚA-Za-z]/.test(s)
function grams(text: string): Map<string, number> {
  const t = text.replace(/[\s「」『』()（）、。,.!?！？:：…・→〜0-9０-９]/g, '')
  const m = new Map<string, number>()
  for (let i = 0; i < t.length - 1; i++) {
    const g = t.slice(i, i + 2)
    if (isKey(g)) m.set(g, (m.get(g) ?? 0) + 1)
  }
  return m
}
const DOCS = Object.entries(TALK).map(([key, e]) => ({ key, e, g: grams(`${e.title} ${e.title} ${e.lines.join(' ')} ${Object.values(e.byType ?? {}).join(' ')}`) }))
const DF = new Map<string, number>()
for (const d of DOCS) for (const g of d.g.keys()) DF.set(g, (DF.get(g) ?? 0) + 1)
const idf = (g: string) => Math.log((DOCS.length + 1) / ((DF.get(g) ?? 0) + 1)) + 1
function vec(m: Map<string, number>) {
  const v = new Map<string, number>()
  let n = 0
  for (const [g, c] of m) { const w = c * idf(g); v.set(g, w); n += w * w }
  return { v, n: Math.sqrt(n) || 1 }
}
const DOC_VECS = DOCS.map(d => ({ ...d, ...vec(d.g) }))

/** text に近いトーク集の項目を、近い順に最大 limit 件返す(levelIds の等級に限る) */
export function findTalk(text: string, levelIds: string[], limit = 3, exclude: string[] = [], minScore = 0.12): { key: string; entry: TalkEntry; score: number }[] {
  const q = vec(grams(text))
  if (q.v.size === 0) return []
  return DOC_VECS
    .filter(d => levelIds.includes(d.key.split(':')[0]) && !exclude.includes(d.key))
    .map(d => {
      let dot = 0
      for (const [g, w] of q.v) { const x = d.v.get(g); if (x) dot += w * x }
      return { key: d.key, entry: d.e, score: dot / (q.n * d.n) }
    })
    .filter(r => r.score >= minScore)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
}
